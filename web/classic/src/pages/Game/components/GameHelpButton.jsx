const GameHelpButton = ({ gameKey, gameName, t }) => {
  const rules = GAME_RULES[gameKey];
  if (!rules) return null;

  const openHelp = (event) => {
    event.stopPropagation();
    Modal.info({
      className: 'game-help-modal',
      title: `${gameName} · ${t('玩法说明')}`,
      width: 520,
      centered: true,
      okText: t('知道了'),
      content: (
        <div className='flex flex-col gap-3 pt-1'>
          {rules.map((rule) => (
            <Text key={rule} style={{ lineHeight: 1.7 }}>
              {t(rule)}
            </Text>
          ))}
        </div>
      ),
    });
  };

  return (
    <Tooltip content={t('查看玩法说明')}>
      <button
        type='button'
        aria-label={t('{{game}}玩法说明', { game: gameName })}
        onClick={openHelp}
        className='game-help-button'
      >
        ?
      </button>
    </Tooltip>
  );
};

export default GameHelpButton;
